/**
 * The known agent a name stands for: an MCP client's own name ("claude-code") or the name a reply is signed with
 * ("Claude"). Undefined for anything else, a person's name included, so ask only about authors that are agents.
 */
export function knownAgent(name: string | null | undefined): KnownAgent | undefined {
    if (!name) return undefined;
    return KNOWN_AGENTS.find((agent) => agent.pattern.test(name));
}

/** An agent's logo as an SVG element in markup, `size` pixels square, in `currentColor`. */
export function agentLogoSvg(agent: KnownAgent, size: number): string {
    const paths = agent.paths.map((d) => `<path d="${d}"/>`).join("");
    return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="currentColor" fill-rule="evenodd" clip-rule="evenodd" aria-hidden="true">${paths}</svg>`;
}
